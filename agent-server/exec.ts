const TEST_MODE = process.env.SHELF_TEST_MODE === '1';

/**
 * Project the app-skill tree to a provider's declared scan path. The provider
 * declares WHERE (`skillTarget`); the agent-server does the fs (provider-boundary
 * principle — providers never touch the filesystem). No-op for providers that
 * need no projection (skillTarget → undefined). Idempotent + atomic, so calling
 * it on every caps/send/reload is safe and collapses to one real creation.
 */
function ensureSkillsProjected(backend: ServerBackend, appId: string | undefined): void {
  const target = backend.skillTarget?.(appId);
  if (!target) return;
  const err = projectAppSkills(appId, target);
  if (err) serverLog('warn', 'skills', err);
}

/**
 * Create a provider's declared config-home BEFORE it spawns its CLI. Some CLIs
 * error if their config-home (auth / config / sessions dir) doesn't pre-exist —
 * codex is one, and a fresh appId with no app-level skills has nothing else that
 * would incidentally create it, so its caps spawn would fail (misreported as
 * "needs auth") without this. The provider only DECLARES the path (`configHome`);
 * the agent-server does the fs (provider-boundary principle). No-op for providers
 * whose CLI self-creates its home (copilot → undefined). Recursive + best-effort:
 * idempotent, so calling it on every caps/send is safe. See agent-providers#16.
 */
function ensureConfigHome(backend: ServerBackend, appId: string | undefined): void {
  const home = backend.configHome?.(appId);
  if (!home) return;
  try {
    fs.mkdirSync(home, { recursive: true });
  } catch (err: any) {
    serverLog('warn', 'config-home', `mkdir ${home} failed: ${err?.message ?? err}`);
  }
}

