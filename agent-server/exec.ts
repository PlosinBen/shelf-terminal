interface IncomingMessage {
  type: 'send' | 'stop' | 'cancel_queued' | 'ping' | 'resolve_permission' | 'resolve_picker' | 'get_capabilities' | 'store_credential' | 'clear_credential' | 'clear_context' | 'read_task_output' | 'stop_task' | 'reload_skills' | 'app_tool_result' | 'cache_reply' | 'start_login' | 'cancel_login' | 'reconnect' | typeof MEMORY_WIRE_TYPE.GET_USAGE;
  provider?: Provider;
  /**
   * For `type: 'send'`: executionId generated by main side so it can pre-register
   * the per-execution event dispatcher before we start emitting. Missing executionId
   * falls back to a freshly-generated one — defensive only; main always sets
   * it in the current architecture.
   */
  executionId?: string;
  prompt?: string;
  cwd?: string;
  resume?: string;
  permissionMode?: string;
  model?: string;
  effort?: string;
  images?: string[];
  attachments?: AgentAttachment[];
  sessionId?: string;
  /**
   * App/tab SESSION routing key (dispatch-layering) — the demux dimension for
   * the out-of-execution messages (`resolve_permission`/`resolve_picker`/`stop_task`)
   * that today route via `activeBackend` ("whoever sent last"). DISTINCT from
   * `sessionId` (the context-store / SDK key). Populated by main now; consumed
   * once the harness routes by sid (group C). Forward-compat seam until then.
   */
  sid?: string;
  /** For `type: 'send'`: a structured config edit (picker / status-bar). When
   *  present, the provider applies it + emits a divider instead of running a
   *  query — prompt is empty for these executions. */
  configEdit?: { key: ConfigEditKey; value: string };
  /** For `type: 'send'` / `type: 'cancel_queued'`: renderer-minted correlation
   *  key. Tracked through the send queue + echoed in the queue snapshot. */
  clientMsgId?: string;
  toolUseId?: string;
  allow?: boolean;
  /** For `type: 'ping'`: client heartbeat sequence, echoed back in pong for RTT. */
  seq?: number;
  /** For `type: 'send'` AND `type: 'get_capabilities'`: app-instance id — names
   *  this app's projected skills dir at `~/.shelf/apps/<appId>/skills` (see
   *  deployment#1). Carried on caps too so config-home providers (copilot --acp)
   *  can set COPILOT_HOME at the caps-time CLI spawn. */
  appId?: string;
  /** resolve_picker payload — picker id minted by provider, payload carries
   * index-aligned answers or { cancelled: true } (see PickerResolvePayload). */
  pickerId?: string;
  payload?: PickerResolvePayload;
  message?: string;
  requestId?: string;
  /** For `type: 'app_tool_result'`: main's reply to an app_tool request. */
  ok?: boolean;
  data?: unknown;
  error?: string;
  key?: string;
  customModels?: ProviderModel[];
  scope?: 'once' | 'session';
  /** For `type: 'read_task_output'`: which background task's remote output_file to read. */
  taskId?: string;
  /**
   * For `type: 'get_capabilities'`: renderer's saved prefs forwarded so
   * session-stateful providers (Copilot) can seed currentModel/currentEffort/
   * currentPermissionMode closures before reporting `current*` back.
   */
  intent?: AgentPrefs;
}

// Session id assigned by the dispatcher at spawn (`--sid=<sid>`); undefined when
// main spawns this exec proc directly (pre-dispatcher / today's path). See send().
const EXEC_SID = process.argv.find((a) => a.startsWith('--sid='))?.split('=')[1];

function send(msg: OutgoingMessage) {
  // Under the dispatcher (dispatch-layering, option B), the exec proc stamps its
  // own `sid` on EVERY outbound message so the dispatcher can relay exec→main RAW
  // — opaque line-forwarding, never parsing the hot token stream — and main demuxes
  // by sid. Spawned directly by main (no --sid), this is a no-op → today's wire.
  const stamped = EXEC_SID ? ({ ...msg, sid: EXEC_SID } as OutgoingMessage) : msg;
  // Wire-TX diagnostic trace (debug level → off by default; flip logLevel=debug
  // to capture). Proves which events the provider actually emitted over stdout —
  // the top of the chain when tracing a sleep/network wedge where tool results
  // never reach the renderer. Skip `type:'log'` to avoid recursion (serverLog
  // routes back through this same send) and log spam. See connection-wedge trace.
  const m = stamped as unknown as Record<string, unknown>;
  if (m.type !== 'log') {
    serverLog('debug', 'wire-tx', wireSummary(m));
  }
  process.stdout.write(JSON.stringify(stamped) + '\n');
}

// ── Model-cache client (dispatch-layering group E) ───────────────────────────
// Only under a dispatcher (EXEC_SID set) is there a per-host cache servicing
// cache_get on its side-channel. Without one, get resolves a MISS → the provider
// fetches as today. `cache_reply` (dispatcher→exec) resolves the pending get.
const pendingCacheGets = new Map<string, (r: { hit: boolean; value?: unknown }) => void>();
let cacheReqSeq = 0;
function resolveCacheReply(requestId: string, hit: boolean, value: unknown): void {
  const r = pendingCacheGets.get(requestId);
  if (r) { pendingCacheGets.delete(requestId); r({ hit, value }); }
}
const modelCacheClient: ModelCacheClient | undefined = EXEC_SID ? {
  get: (key, provider) => new Promise((resolve) => {
    const requestId = `cg-${cacheReqSeq++}`;
    pendingCacheGets.set(requestId, resolve);
    send({ type: 'cache_get', requestId, key, provider } as unknown as OutgoingMessage);
    // Safety net: a slow/absent dispatcher must not hang init → resolve a miss.
    // A timeout is a real anomaly (the dispatcher should always reply) → fail-loud.
    setTimeout(() => {
      if (pendingCacheGets.delete(requestId)) {
        serverLog('warn', 'cache', `cache_get ${key}:${provider} timed out (no dispatcher reply in 2s) — treating as miss`);
        resolve({ hit: false });
      }
    }, 2000).unref?.();
  }),
  put: (key, provider, value) => { send({ type: 'cache_put', key, provider, value } as unknown as OutgoingMessage); },
} : undefined;

/** Compact one-line summary of a wire message for the wire-tx/wire-rx traces. */
function wireSummary(m: Record<string, unknown>): string {
  const bit = (k: string, v: unknown) => (v == null ? '' : ` ${k}=${String(v).slice(0, 12)}`);
  return `type=${String(m.type)}${bit('execution', m.executionId)}${bit('msgType', m.msgType)}${bit('msgId', m.msgId)}`
    + (typeof m.content === 'string' ? ` len=${m.content.length}` : '');
}

