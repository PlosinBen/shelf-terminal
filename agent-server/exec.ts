const rl = readline.createInterface({ input: process.stdin, terminal: false });

// ── Server-owned send queue ──────────────────────────────────────────────────
// The client (renderer) eager-sends every submission; THIS side owns the timing
// (排序 + 釋放時機). The queue serializes executions one-at-a-time (concurrent execution
// handlers would race on the provider backend's module-level state — activeExecutionSend
// / abortController / activeQuery / lastSessionId) AND is introspectable so we
// emit a snapshot the renderer mirrors. Logic lives in the pure `createSendQueue`
// factory (send-queue.ts, unit-tested). See message-queue-ownership design.
const sendQueue = createSendQueue<IncomingMessage>({
  handle: (msg) => handleSend(msg),
  // Session-level (no executionId) so main routes it to the `onQueue` sink.
  emitSnapshot: (items) => send({ type: 'queue', items }),
  // Dropped queued send → terminal idle on its executionId, or main's per-execution
  // generator (registered before the send was sent) hangs forever.
  terminateExecution: (executionId) => send({ type: 'status', state: 'idle', executionId } as OutgoingMessage),
  onHandleError: (msg, err) => {
    const tid = msg.executionId ?? '';
    send({ type: 'error', error: (err as any)?.message ?? String(err), executionId: tid } as OutgoingMessage);
    send({ type: 'status', state: 'idle', executionId: tid } as OutgoingMessage);
  },
  // Never silent: a cancel that didn't cleanly remove a queued item. 'cancel-
  // running' is a benign race (snapshot re-promotes); 'cancel-unknown' is a real
  // desync worth investigating → warn, routed to main's logger over the wire.
  onAnomaly: (reason, clientMsgId) => {
    serverLog('warn', 'send-queue', `${reason} clientMsgId=${clientMsgId}`);
  },
});

rl.on('line', (line) => {
  let msg: IncomingMessage;
  try {
    msg = JSON.parse(line);
  } catch {
    send({ type: 'error', error: 'Invalid JSON' });
    return;
  }

  switch (msg.type) {
    case 'send':
      sendQueue.enqueue(msg);
      break;
    case 'cancel_queued':
      if (typeof msg.clientMsgId === 'string') sendQueue.cancel(msg.clientMsgId);
      break;
    case 'stop':
      // ESC: clear the waiting queue (server is the queue authority now) +
      // interrupt the running execution. clear() emits the updated snapshot.
      sendQueue.clear();
      if (typeof msg.requestId === 'string') {
        void handleStop().then(
          () => send({ type: 'stop_result', requestId: msg.requestId!, ok: true }),
          (err) => {
            const error = (err as Error)?.message ?? String(err);
            serverLog('error', 'stop', `${error} reqId=${msg.requestId}`);
            send({ type: 'stop_result', requestId: msg.requestId!, ok: false, error });
          },
        );
      } else {
        // Legacy/non-RPC caller: still fail loud if provider cancellation fails.
        void handleStop().catch((err) => serverLog('error', 'stop', (err as Error)?.message ?? String(err)));
      }
      break;
    case 'ping':
      // Heartbeat: echo `seq` (client measures RTT on its own clock), refresh the
      // version-dir liveness lease the cleanup sweep reads (§5.9), and reset the
      // ssh idle-shutdown watchdog (the client is alive).
      send({ type: 'pong', seq: msg.seq });
      touchHeartbeats();
      resetWatchdog();
      break;
    case MEMORY_WIRE_TYPE.GET_USAGE:
      void reportMemoryUsage();
      break;
    case 'resolve_permission':
      if (activeBackend && msg.toolUseId !== undefined) {
        activeBackend.resolvePermission?.(msg.toolUseId, msg.allow ?? false, msg.message, msg.scope);
      }
      break;
    case 'resolve_picker':
      if (activeBackend && msg.pickerId !== undefined && msg.payload !== undefined) {
        activeBackend.resolvePicker?.(msg.pickerId, msg.payload);
      }
      break;
    case 'app_tool_result':
      // main's reply to an app_tool request — resolve the awaiting bridge tool.
      if (typeof msg.requestId === 'string') {
        resolveAppToolResult(msg.requestId, { ok: msg.ok ?? false, data: msg.data, error: msg.error });
      }
      break;
    case 'cache_reply':
      // dispatcher's answer to a cache_get (group E) — resolve the pending get.
      if (typeof msg.requestId === 'string') {
        resolveCacheReply(msg.requestId, (msg as any).hit ?? false, (msg as any).value);
      }
      break;
    case 'stop_task':
      // Fire-and-forget: the provider stops the task; the resulting
      // task_notification('stopped') flows back via the task_event lane.
      if (activeBackend && msg.taskId !== undefined) {
        void activeBackend.stopTask?.(msg.taskId);
      }
      break;
    case 'get_capabilities': {
      const provider = msg.provider ?? CLAUDE_PROVIDER;
      (async () => {
        try {
          const backend = getBackend(provider);
          // Create the config-home + project skills before caps — the CLI spawns
          // during gatherCapabilities (config-home providers), so both must exist
          // by then (codex errors if CODEX_HOME is absent → misreported as auth).
          ensureConfigHome(backend, msg.appId);
          ensureSkillsProjected(backend, msg.appId);
          const restoreContext = loadRestoreContextFor(provider, msg.sessionId);
          backend.bindSessionSend?.(wrapSendForContext(provider, msg.sessionId, send));
          const caps = await backend.gatherCapabilities?.(
            msg.cwd ?? process.cwd(),
            msg.sessionId,
            msg.customModels,
            msg.intent,
            modelCacheClient,
            msg.appId,
            restoreContext,
          );
          send({ type: 'capabilities', requestId: msg.requestId ?? '', ...(caps ?? {}) });
        } catch (err: any) {
          // Real data loss: gatherCapabilities threw → response carries only
          // `error`, and remote.ts resolves an all-empty caps (perm modes vanish).
          // Loud so the true cause (e.g. Copilot listModels network throw) is visible.
          serverLog('error', 'caps', `${provider} gatherCapabilities threw: ${err?.message ?? err} reqId=${msg.requestId ?? ''}`);
          send({ type: 'capabilities', requestId: msg.requestId ?? '', error: err?.message ?? String(err) });
        }
      })();
      break;
    }
    case 'store_credential': {
      const provider = msg.provider ?? CLAUDE_PROVIDER;
      (async () => {
        try {
          const backend = getBackend(provider);
          if (!backend.storeCredential) throw new Error(`Provider ${provider} does not accept API keys`);
          await backend.storeCredential(msg.key ?? '');
          send({ type: 'credential_stored', requestId: msg.requestId ?? '', ok: true });
        } catch (err: any) {
          send({ type: 'credential_stored', requestId: msg.requestId ?? '', ok: false, error: err?.message ?? String(err) });
        }
      })();
      break;
    }
    case 'clear_credential': {
      const provider = msg.provider ?? CLAUDE_PROVIDER;
      (async () => {
        try {
          const backend = getBackend(provider);
          if (!backend.clearCredential) throw new Error(`Provider ${provider} has no credential to clear`);
          await backend.clearCredential();
          send({ type: 'credential_cleared', requestId: msg.requestId ?? '', ok: true });
        } catch (err: any) {
          send({ type: 'credential_cleared', requestId: msg.requestId ?? '', ok: false, error: err?.message ?? String(err) });
        }
      })();
      break;
    }
    case 'read_task_output': {
      const provider = msg.provider ?? CLAUDE_PROVIDER;
      (async () => {
        try {
          const backend = getBackend(provider);
          if (!backend.readTaskOutput) throw new Error(`Provider ${provider} does not support reading task output`);
          const content = await backend.readTaskOutput(msg.taskId ?? '');
          send({ type: 'task_output', requestId: msg.requestId ?? '', content });
        } catch (err: any) {
          send({ type: 'task_output', requestId: msg.requestId ?? '', error: err?.message ?? String(err) });
        }
      })();
      break;
    }
    case 'reload_skills':
      // App-level skills changed: main refreshed the L1 canonical tree. Re-project
      // each provider's L2 target (central — agent-server owns the fs; a no-op for
      // symlink providers since the live source is already followed, real work for
      // copy-mode), THEN tell EVERY provider to re-scan on its live session. App
      // skills are app-global, not per-session; each reload is best-effort + no-op
      // without a live session. Emit a `skills_reloaded` result via the BASE send.
      for (const b of backendRegistry.values()) ensureSkillsProjected(b, lastAppId);
      for (const b of backendRegistry.values()) {
        void b.reloadSkills?.().then((r) => {
          if (r && r.reloaded) send({ type: 'skills_reloaded', ok: r.ok, ...(r.error ? { error: r.error } : {}) });
        });
      }
      break;
    case 'start_login': {
      // Interactive device-flow login (fire-and-forget). The provider spawns its
      // CLI login, forwards the parsed prompt via the BASE `send` (executionId-less,
      // like auth_required), and emits auth_login_done on exit. See
      // features copilot-device-login.
      const provider = msg.provider ?? COPILOT_PROVIDER;
      try {
        const backend = getBackend(provider);
        if (!backend.startLogin) {
          send({ type: 'auth_login_done', provider, ok: false, error: `Provider ${provider} has no interactive login` });
          break;
        }
        backend.startLogin(msg.cwd ?? process.cwd(), send);
      } catch (err: any) {
        send({ type: 'auth_login_done', provider, ok: false, error: err?.message ?? String(err) });
      }
      break;
    }
    case 'cancel_login':
      // Best-effort: cancel a running login on whichever backend is active.
      activeBackend?.cancelLogin?.();
      break;
    case 'reconnect': {
      // Post-login re-init (Gap C): drop the provider's live ACP connection so the
      // next caps/execution respawns and re-reads the config-home credentials the device-
      // login just wrote. No-op for providers without a long-lived process. main
      // sends this right before re-fetching capabilities (order preserved by the
      // FIFO stdin stream — reconnect runs synchronously before get_capabilities).
      const provider = msg.provider ?? COPILOT_PROVIDER;
      try {
        getBackend(provider).reconnect?.();
      } catch (err: any) {
        serverLog('warn', 'exec', `reconnect failed: ${err?.message ?? err}`, { provider });
      }
      break;
    }
    case 'clear_context': {
      if (msg.sessionId) {
        deleteContext(msg.sessionId);
        // Tell every provider that has cached state for this session to drop it,
        // so they don't try to resume from a now-deleted lastSdkSessionId on
        // the next execution. Sync per-backend call — they just clear in-memory refs.
        for (const b of backendRegistry.values()) b.resetSession?.(msg.sessionId);
      }
      break;
    }
    default: {
      // Fail-loud on an unknown wire command instead of silently dropping it —
      // a main↔agent-server protocol drift must leave a trace, not vanish.
      serverLog('warn', 'exec', 'unknown incoming message type — ignored', { type: (msg as any)?.type });
      break;
    }
  }
});

// Every NORMAL agent-server closure funnels through shutdown(): reap escaped
// detached tasks, dispose backends, exit. Called from BOTH the stdin-close handler
// and the idle watchdog; `shuttingDown` makes it idempotent (both can fire). It
// ALWAYS reaps — a closure while we're alive is a real end of session (no
// reconnect). Only an ABNORMAL closure (agent-server itself died) skips this →
// crash net (Phase 2). Reap timeout is bounded so a hung provider RPC can't stall.
let shuttingDown = false;
const REAP_TIMEOUT_MS = 2000;

async function shutdown(): Promise<void> {
  if (shuttingDown) return;
  shuttingDown = true;
  await performShutdown({
    backends: backendRegistry.values(),
    reapTimeoutMs: REAP_TIMEOUT_MS,
    log: (level, msg) => serverLog(level, 'reaper', msg),
    // Normal closure: we just reaped our own detached tasks, so drop our crash-net
    // lease — next launch must NOT sweep a session that shut down cleanly.
    exit: () => {
      removeSessionLease(SHELF_SESSION);
      process.exit(0);
    },
  });
}

rl.on('close', () => {
  void shutdown();
});

